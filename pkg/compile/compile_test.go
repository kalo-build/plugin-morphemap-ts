func (suite *CompileTestSuite) TestMorpheMapToTypeScript_NoMapsError() {
	emptyDir := filepath.Join(suite.TestDirPath, "working-ts-empty")
	suite.Nil(os.Mkdir(emptyDir, 0755))
	defer os.RemoveAll(emptyDir)

	mapsDir := filepath.Join(suite.TestDirPath, "working-ts-empty-maps")
	suite.Nil(os.Mkdir(mapsDir, 0755))
	defer os.RemoveAll(mapsDir)

	config := compile.TsConverterConfig{
		MapsPath: mapsDir,
		RegistryConfig: rcfg.MorpheLoadRegistryConfig{
			RegistryModelsDirPath:     suite.ModelsDirPath,
			RegistryEnumsDirPath:      suite.EnumsDirPath,
			RegistryStructuresDirPath: suite.StructuresDirPath,
			RegistryEntitiesDirPath:   suite.EntitiesDirPath,
		},
		OutputPath:            emptyDir,
		SourceTypesImportPath: "@/types/source",
		TargetTypesImportPath: "@/types/target",
	}

	compileErr := compile.MorpheMapToTypeScript(config)

	suite.Error(compileErr)
	suite.Contains(compileErr.Error(), "no .map files found")
}
